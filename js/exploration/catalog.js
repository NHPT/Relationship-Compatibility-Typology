function explorationQuestion(topicId, facet, text, options, mode = 'scenario') {
  const topic = EXPLORATION_TOPICS.find(topic => topic.id === topicId);
  const facetIndex = topic.facets.indexOf(facet);
  if (facetIndex < 0) throw new Error(`未登记的内容：${topicId} ${facet}`);
  const id = `ex-${topicId}-${facetIndex + 1}`;
  return {
    id, topicId, facet, text, mode,
    options: options.map((text, index) => ({ id: `${id}:${index}`, text }))
  };
}
function getExplorationGroup(groupId) {
  const group = EXPLORATION_GROUPS.find(group => group.id === groupId);
  if (!group) throw new Error('请选择有效的探索主题组');
  return group;
}
function explorationQuestions(groupId) {
  return getExplorationGroup(groupId).topics.flatMap(id => EXPLORATION_BANK[id]);
}
